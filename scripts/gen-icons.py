#!/usr/bin/env python3
"""
Generate the launcher's pixel-art icons: one per system, Favorites and
Recently Played, and the header ship. (Settings keeps its gear glyph.)

    python gen-icons.py <launcher/icons.h> [preview.png]

All art here is original, drawn for this project as 16x16 pixel sprites: a
console's silhouette in its colours, not any company's logo or artwork, so the
icons carry no licence question. The launcher scales them by whole pixels
(nearest neighbour), which keeps the edges crisp at any resolution.

Writes the C header the launcher includes (committed, so a build does not need
Python). The preview PNG needs Pillow (Windows' python has it; WSL's does not).

Each icon: a palette (one character per colour, '.' is transparent) and 16 rows
of 16 characters. Keys are the launcher's system dir_name, or one of the
special names below.
"""
import sys

ICONS = {}


def icon(name, palette, art):
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) == 16, f'{name}: {len(rows)} rows'
    for i, r in enumerate(rows):
        assert len(r) == 16, f'{name} row {i}: {len(r)} columns: {r!r}'
        for c in r:
            assert c == '.' or c in palette, f'{name} row {i}: colour {c!r} not in palette'
    ICONS[name] = (palette, rows)


