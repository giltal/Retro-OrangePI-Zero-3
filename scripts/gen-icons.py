def ring_icon(name, colour, gap, extra):
    """A 2-pixel ring (radius 5..7) with a gap between the angles in `gap`
    (degrees, 0 = right, 90 = up), plus extra pixels drawn on top."""
    import math
    grid = [['.'] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            dx, dy = x - 7.5, 7.5 - y
            r = math.hypot(dx, dy)
            a = math.degrees(math.atan2(dy, dx)) % 360
            if 4.8 <= r <= 7.2 and not (gap[0] <= a <= gap[1]):
                grid[y][x] = 'C'
    for (y, x) in extra:
        grid[y][x] = 'C'
    icon(name, {'C': colour}, '\n'.join(''.join(r) for r in grid))


