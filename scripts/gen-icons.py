def scale2x(rows):
    """Scale2x (EPX): doubles a pixel-art grid, rounding the staircase edges of
    diagonals and curves. It only ever copies a neighbour's colour, so the
    palette is unchanged. '.' (transparent) takes part like a colour, which
    smooths the outline too."""
    h, w = len(rows), len(rows[0])
    px = lambda y, x: rows[y][x] if 0 <= y < h and 0 <= x < w else '.'
    out = [[''] * (2 * w) for _ in range(2 * h)]
    for y in range(h):
        for x in range(w):
            P = px(y, x)
            A, B, C, D = px(y - 1, x), px(y, x + 1), px(y, x - 1), px(y + 1, x)
            out[2 * y][2 * x] = A if (C == A and C != D and A != B) else P
            out[2 * y][2 * x + 1] = B if (A == B and A != C and B != D) else P
            out[2 * y + 1][2 * x] = C if (D == C and D != B and C != A) else P
            out[2 * y + 1][2 * x + 1] = D if (B == D and B != A and D != C) else P
    return [''.join(r) for r in out]


UPSCALE = 2     # Scale2x passes: 16x16 art -> 64x64 icons

# Kept at their 16x16 pixels (the launcher scales them up by whole pixels):
# the header ship, whose blocky look the user preferred.
NO_UPSCALE = {'ship'}


def hires(rows, name=None):
    if name in NO_UPSCALE:
        return rows
    for _ in range(UPSCALE):
        rows = scale2x(rows)
    return rows


def write_header(path):
    out = ['/* Generated by scripts/gen-icons.py -- do not edit. Original pixel art,',
           ' * drawn at 16x16 for this project (no logos or third-party artwork),',
           ' * upscaled with Scale2x to ICON_SIZE (the header ship stays 16x16). */',
           '#pragma once',
           '#include <stdint.h>',
           '',
           'typedef struct {',
           '    const char *name;       /* g_systems[].dir_name, or favorites/recents/ship */',
           '    int size;               /* pixels per side: ICON_SIZE, or 16 */',
           '    uint32_t palette[9];    /* 0xRRGGBB, indexed by the digits in pixels */',
           '    const char *pixels;     /* size rows of size: \'.\' transparent, \'0\'..\'8\' palette */',
           '} PixelIcon;',
           '',
           f'#define ICON_SIZE {16 << UPSCALE}',
           '',
           'static const PixelIcon g_icons[] = {']
    for name, (palette, rows) in ICONS.items():
        keys = list(palette)
        assert len(keys) <= 9, f'{name}: more than 9 colours'
        pal = ', '.join(f'0x{palette[k]}' for k in keys)
        px = hires(rows, name)
        out.append(f'    {{ "{name}", {len(px)}, {{ {pal} }},')
        for r in px:
            out.append('      "' + ''.join('.' if c == '.' else str(keys.index(c)) for c in r) + '"')
        out[-1] += ' },'
    out += ['};', '']
    open(path, 'w', newline='\n').write('\n'.join(out))


def write_preview(path, scale=1):
    """The icons as the launcher draws them: 64x64, one image pixel each."""
    from PIL import Image, ImageDraw
    names = list(ICONS)
    cols = 8
    cell = (16 << UPSCALE) * scale + 24
    img = Image.new('RGB', (cols * cell, ((len(names) + cols - 1) // cols) * (cell + 18)), (16, 24, 40))
    d = ImageDraw.Draw(img)
    for i, name in enumerate(names):
        palette, rows = ICONS[name]
        rows = hires(rows, name)
        ox, oy = (i % cols) * cell + 12, (i // cols) * (cell + 18) + 8
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c != '.':
                    col = tuple(int(palette[c][j:j + 2], 16) for j in (0, 2, 4))
                    d.rectangle([ox + x * scale, oy + y * scale, ox + (x + 1) * scale - 1, oy + (y + 1) * scale - 1], fill=col)
        d.text((ox, oy + len(rows) * scale + 2), name, fill=(220, 226, 236))
    img.save(path)


if __name__ == '__main__':
    write_header(sys.argv[1])
    if len(sys.argv) > 2:
        write_preview(sys.argv[2])
    print(f'{len(ICONS)} icons')
